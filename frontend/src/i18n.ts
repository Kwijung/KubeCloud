export const messages: Record<Language, Messages> = { ko, en };

type I18n = {
  language: Language;
  setLanguage: (language: Language) => void;
  t: Messages;
  // errorText explains a backend error code, falling back to the server's message.
  errorText: (error: unknown) => string;
  statusText: (status: string) => string;
};

const I18nContext = createContext<I18n | null>(null);

function initialLanguage(): Language {
  try {
    const stored = window.localStorage.getItem("kloudia-language");
    if (stored === "en" || stored === "ko") {
      return stored;
    }
  } catch {
    // Storage can be unavailable (private mode); fall back to Korean.
  }
  return "ko";
}

export function I18nProvider({ children }: { children: ReactNode }) {
  const [language, setLanguage] = useState<Language>(initialLanguage);
  useEffect(() => {
    try {
      window.localStorage.setItem("kloudia-language", language);
    } catch {
      // Not persisted; the choice still applies to this page.
    }
    document.documentElement.lang = language;
  }, [language]);
  const value = useMemo<I18n>(() => {
    const t = messages[language];
    return {
      language,
      setLanguage,
      t,
      errorText: (error) => errorText(t, error),
      statusText: (status) => statusText(t, status),
    };
  }, [language]);
  return createElement(I18nContext.Provider, { value }, children);
}

export function useI18n(): I18n {
  const value = useContext(I18nContext);
  if (!value) {
    throw new Error("useI18n outside I18nProvider");
  }
  return value;
}

export function errorText(t: Messages, error: unknown): string {
  if (typeof error === "object" && error !== null && "code" in error) {
    const key = `error${String((error as { code: unknown }).code)}` as keyof Messages;
    if (key in t) {
      return t[key];
    }
  }
  if (error instanceof Error && error.message) {
    return `${t.requestFailed}: ${error.message}`;
  }
  return t.requestFailed;
}

const statusKeys: Record<string, keyof Messages> = {
  running: "statusRunning",
  stopped: "statusStopped",
  provisioning: "statusProvisioning",
  importing: "statusImporting",
  starting: "statusStarting",
  stopping: "statusStopping",
  ready: "statusReady",
  available: "statusReady",
  failed: "statusFailed",
  missing: "statusMissing",
  pending: "statusPending",
  ok: "statusOk",
  degraded: "statusDegraded",
  warning: "statusWarning",
  warn: "statusWarning",
};

export function statusText(t: Messages, status: string): string {
  const key = statusKeys[status.toLowerCase()];
  return key ? t[key] : status;
}

export function statusTone(status: string): Tone {
  switch (status.toLowerCase()) {
    case "running":
    case "ready":
    case "available":
    case "ok":
      return "success";
    case "failed":
    case "missing":
    case "error":
      return "error";
    case "provisioning":
    case "importing":
    case "starting":
    case "stopping":
    case "pending":
      return "info";
    case "degraded":
    case "warning":
    case "warn":
      return "warning";
    default:
      return "neutral";
  }
}
